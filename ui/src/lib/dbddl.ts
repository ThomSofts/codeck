// Alterações de estrutura (DDL) escritas para cada banco: renomear/apagar/esvaziar tabela, colunas (incluir, renomear,
// tipo, nulo, padrão, descrição, excluir), índices, descrição da tabela e a tabela nova. Só monta o SQL — quem executa é
// a bancada, depois de mostrar o texto (e com as regras de produção de sempre: destravar, transação, Confirmar/Desfazer).
import type { Engine, TableInfo } from "./db.svelte";

export type TableRef = { schema: string; name: string };
export type TCol = TableInfo["columns"][number] & { comment?: string };
/** Coluna como a pessoa descreveu no formulário. default = expressão SQL crua ("0", "'ativo'", "CURRENT_TIMESTAMP"). */
/** O que o editor de estrutura está montando. */
export type EditKind = { kind: "column"; col: TCol | null } | { kind: "index" } | { kind: "table"; schema: string };
export interface ColDef { name: string; type: string; nullable: boolean; default: string; identity: boolean; pk: boolean; comment: string }
type E = Exclude<Engine, "mongodb" | "firebase" | "redis">;

/** Bancos em que a estrutura é editável por aqui (os de documento não têm esquema fixo). */
export const canAlter = (e: Engine | null | undefined): e is E => e === "postgres" || e === "sqlserver" || e === "mysql" || e === "sqlite" || e === "libsql";
const lite = (e: E) => e === "sqlite" || e === "libsql";

export const TYPES: Record<E, string[]> = {
  postgres: ["integer", "bigint", "smallint", "numeric(12,2)", "text", "varchar(255)", "boolean", "date", "timestamp", "timestamptz", "uuid", "jsonb",
    "double precision", "real", "time", "bytea", "char(1)", "interval", "inet"],
  sqlserver: ["int", "bigint", "smallint", "tinyint", "bit", "decimal(18,2)", "money", "nvarchar(255)", "nvarchar(max)", "varchar(255)", "char(10)",
    "date", "datetime", "datetime2(7)", "time(7)", "uniqueidentifier", "float", "varbinary(max)", "xml"],
  mysql: ["int", "bigint", "tinyint(1)", "smallint", "decimal(12,2)", "varchar(255)", "char(36)", "text", "longtext", "json", "date", "datetime",
    "timestamp", "time", "double", "float", "blob", "enum('a','b')"],
  sqlite: ["INTEGER", "TEXT", "REAL", "NUMERIC", "BLOB"],
  libsql: ["INTEGER", "TEXT", "REAL", "NUMERIC", "BLOB"],
};

export function q(e: E, id: string) {
  return e === "sqlserver" ? `[${id.replace(/]/g, "]]")}]` : e === "mysql" ? "`" + id.replace(/`/g, "``") + "`" : `"${id.replace(/"/g, '""')}"`;
}
/** Texto como literal SQL (o SQL Server com N'' para não perder acentos). */
export const lit = (e: E, s: string) => (e === "sqlserver" ? "N" : "") + `'${s.replace(/'/g, "''")}'`;
/** Nome completo da tabela (no SQLite, sem o "main."). */
export const tbl = (e: E, t: TableRef) => (lite(e) || !t.schema ? q(e, t.name) : `${q(e, t.schema)}.${q(e, t.name)}`);
const dfName = (t: TableRef, col: string) => `DF_${t.name}_${col}`.replace(/[^\w]/g, "_").slice(0, 120);

/** SQL Server: a descrição (MS_Description) — atualiza se existe, cria se não, remove se ficou vazia. */
function msDescription(t: TableRef, col: string | null, text: string) {
  const L = (s: string) => lit("sqlserver", s);
  const obj = L(`${q("sqlserver", t.schema)}.${q("sqlserver", t.name)}`);
  const minor = col ? `COLUMNPROPERTY(OBJECT_ID(${obj}), ${L(col)}, 'ColumnId')` : "0";
  const target = `N'SCHEMA', ${L(t.schema)}, N'TABLE', ${L(t.name)}${col ? `, N'COLUMN', ${L(col)}` : ""}`;
  const exists = `EXISTS (SELECT 1 FROM sys.extended_properties WHERE class = 1 AND major_id = OBJECT_ID(${obj}) AND minor_id = ${minor} AND name = N'MS_Description')`;
  if (!text.trim()) return `IF ${exists}\n  EXEC sp_dropextendedproperty N'MS_Description', ${target};`;
  return `IF ${exists}\n  EXEC sp_updateextendedproperty N'MS_Description', ${L(text)}, ${target};\nELSE\n  EXEC sp_addextendedproperty N'MS_Description', ${L(text)}, ${target};`;
}
/** SQL Server: remove o DEFAULT da coluna (o nome da restrição é gerado pelo servidor — é preciso descobrir). */
function msDropDefault(t: TableRef, col: string) {
  const T = tbl("sqlserver", t), obj = lit("sqlserver", T);
  return `DECLARE @df sysname = (SELECT dc.name FROM sys.default_constraints dc JOIN sys.columns c ON c.default_object_id = dc.object_id
  WHERE c.object_id = OBJECT_ID(${obj}) AND c.name = ${lit("sqlserver", col)});
IF @df IS NOT NULL EXEC (N'ALTER TABLE ${T.replace(/'/g, "''")} DROP CONSTRAINT [' + @df + N']');`;
}

/** A definição da coluna (nome, tipo, identidade, nulo, padrão) como vai num CREATE/ADD. */
function colSql(e: E, t: TableRef, c: ColDef, o: { create?: boolean; inlinePk?: boolean } = {}) {
  let s = `${q(e, c.name)} ${c.type.trim()}`;
  if (c.identity) {
    if (e === "postgres") s += " GENERATED BY DEFAULT AS IDENTITY";
    else if (e === "sqlserver") s += " IDENTITY(1,1)";
    else if (e === "mysql") s += " AUTO_INCREMENT";
  }
  if (o.inlinePk) s += lite(e) && c.identity ? " PRIMARY KEY AUTOINCREMENT" : " PRIMARY KEY";
  else s += c.nullable && !c.pk ? " NULL" : " NOT NULL";
  if (c.default.trim() && !c.identity) s += e === "sqlserver" ? ` CONSTRAINT ${q(e, dfName(t, c.name))} DEFAULT (${c.default.trim()})` : ` DEFAULT ${c.default.trim()}`;
  if (e === "mysql" && c.comment.trim()) s += ` COMMENT ${lit(e, c.comment)}`;
  return s;
}

export function renameTable(e: E, t: TableRef, to: string): string[] {
  if (e === "sqlserver") return [`EXEC sp_rename ${lit(e, tbl(e, t))}, ${lit(e, to)};`];
  if (e === "mysql") return [`RENAME TABLE ${tbl(e, t)} TO ${tbl(e, { schema: t.schema, name: to })};`];
  return [`ALTER TABLE ${tbl(e, t)} RENAME TO ${q(e, to)};`];
}
export const dropTable = (e: E, t: TableRef, view = false) => [`DROP ${view ? "VIEW" : "TABLE"} ${tbl(e, t)};`];
export const truncateTable = (e: E, t: TableRef) => [lite(e) ? `DELETE FROM ${tbl(e, t)};` : `TRUNCATE TABLE ${tbl(e, t)};`];

export function addColumn(e: E, t: TableRef, c: ColDef): string[] {
  const out = [`ALTER TABLE ${tbl(e, t)} ADD ${e === "sqlserver" ? "" : "COLUMN "}${colSql(e, t, { ...c, pk: false })};`];
  if (c.comment.trim()) {
    if (e === "postgres") out.push(`COMMENT ON COLUMN ${tbl(e, t)}.${q(e, c.name)} IS ${lit(e, c.comment)};`);
    if (e === "sqlserver") out.push(msDescription(t, c.name, c.comment));
  }
  return out;
}
export function dropColumn(e: E, t: TableRef, col: string): string[] {
  const d = `ALTER TABLE ${tbl(e, t)} DROP COLUMN ${q(e, col)};`;
  return e === "sqlserver" ? [msDropDefault(t, col), d] : [d];
}
export function renameColumn(e: E, t: TableRef, from: string, to: string): string[] {
  if (e === "sqlserver") return [`EXEC sp_rename ${lit(e, `${tbl(e, t)}.${q(e, from)}`)}, ${lit(e, to)}, N'COLUMN';`];
  return [`ALTER TABLE ${tbl(e, t)} RENAME COLUMN ${q(e, from)} TO ${q(e, to)};`];
}

/** Tipo, nulo, padrão e descrição de uma coluna que já existe. O nome muda à parte (renameColumn), antes. */
export function alterColumn(e: E, t: TableRef, before: TCol, after: ColDef): { sql: string[]; warn?: string; error?: string } {
  const T = tbl(e, t), C = q(e, after.name);
  const typeCh = after.type.trim().toLowerCase() !== before.type.toLowerCase();
  const nullCh = after.nullable !== before.nullable;
  const defCh = after.default.trim() !== (before.default ?? "").trim();
  const comCh = after.comment.trim() !== (before.comment || "").trim();
  if (!typeCh && !nullCh && !defCh && !comCh) return { sql: [] };
  if (lite(e)) {
    if (typeCh || nullCh || defCh) return { sql: [], error: "O SQLite não muda tipo, nulo ou padrão de uma coluna que já existe. O caminho é criar a tabela nova com a estrutura certa, copiar os dados e trocar os nomes." };
    return { sql: [], error: "O SQLite não guarda descrição de coluna." };
  }
  const out: string[] = [];
  if (e === "postgres") {
    const parts: string[] = [];
    if (typeCh) parts.push(`ALTER COLUMN ${C} TYPE ${after.type.trim()} USING ${C}::${after.type.trim()}`);
    if (nullCh) parts.push(`ALTER COLUMN ${C} ${after.nullable ? "DROP NOT NULL" : "SET NOT NULL"}`);
    if (defCh) parts.push(after.default.trim() ? `ALTER COLUMN ${C} SET DEFAULT ${after.default.trim()}` : `ALTER COLUMN ${C} DROP DEFAULT`);
    if (parts.length) out.push(`ALTER TABLE ${T}\n  ${parts.join(",\n  ")};`);
    if (comCh) out.push(`COMMENT ON COLUMN ${T}.${C} IS ${after.comment.trim() ? lit(e, after.comment) : "NULL"};`);
    return { sql: out };
  }
  if (e === "sqlserver") {
    if (typeCh || nullCh) out.push(`ALTER TABLE ${T} ALTER COLUMN ${C} ${after.type.trim()} ${after.nullable ? "NULL" : "NOT NULL"};`);
    if (defCh) {
      out.push(msDropDefault(t, after.name));
      if (after.default.trim()) out.push(`ALTER TABLE ${T} ADD CONSTRAINT ${q(e, dfName(t, after.name))} DEFAULT (${after.default.trim()}) FOR ${C};`);
    }
    if (comCh) out.push(msDescription(t, after.name, after.comment));
    return { sql: out };
  }
  // MySQL/MariaDB: MODIFY reescreve a definição inteira da coluna
  let s = `ALTER TABLE ${T} MODIFY COLUMN ${C} ${after.type.trim()} ${after.nullable ? "NULL" : "NOT NULL"}`;
  if (after.default.trim()) s += ` DEFAULT ${after.default.trim()}`;
  if (before.identity) s += " AUTO_INCREMENT";
  if (after.comment.trim()) s += ` COMMENT ${lit(e, after.comment)}`;
  return { sql: [s + ";"], warn: "No MySQL a coluna é reescrita inteira (MODIFY): atributos que não aparecem aqui — ON UPDATE, charset, collation — voltam ao padrão." };
}

export function tableComment(e: E, t: TableRef, text: string): string[] {
  if (e === "postgres") return [`COMMENT ON TABLE ${tbl(e, t)} IS ${text.trim() ? lit(e, text) : "NULL"};`];
  if (e === "sqlserver") return [msDescription(t, null, text)];
  if (e === "mysql") return [`ALTER TABLE ${tbl(e, t)} COMMENT = ${lit(e, text)};`];
  return [];
}

export function createIndex(e: E, t: TableRef, name: string, cols: string[], unique: boolean): string[] {
  return [`CREATE ${unique ? "UNIQUE " : ""}INDEX ${q(e, name)} ON ${tbl(e, t)} (${cols.map(c => q(e, c)).join(", ")});`];
}
export function dropIndex(e: E, t: TableRef, name: string): string[] {
  if (e === "postgres") return [`DROP INDEX ${q(e, t.schema)}.${q(e, name)};`];
  if (lite(e)) return [`DROP INDEX ${q(e, name)};`];
  return [`DROP INDEX ${q(e, name)} ON ${tbl(e, t)};`];
}

export function createTable(e: E, t: TableRef, cols: ColDef[], comment = ""): string[] {
  const pk = cols.filter(c => c.pk);
  // SQLite: INTEGER PRIMARY KEY sozinha (com numeração) vai na própria coluna — é o rowid
  const inline = lite(e) && pk.length === 1 && /^integer$/i.test(pk[0].type.trim()) ? pk[0].name : null;
  const lines = cols.map(c => "  " + colSql(e, t, c, { create: true, inlinePk: c.name === inline }));
  if (pk.length && !inline) lines.push(`  CONSTRAINT ${q(e, `PK_${t.name}`.replace(/[^\w]/g, "_"))} PRIMARY KEY (${pk.map(c => q(e, c.name)).join(", ")})`);
  let s = `CREATE TABLE ${tbl(e, t)} (\n${lines.join(",\n")}\n)`;
  if (e === "mysql" && comment.trim()) s += ` COMMENT = ${lit(e, comment)}`;
  const out = [s + ";"];
  if (e === "postgres") {
    if (comment.trim()) out.push(`COMMENT ON TABLE ${tbl(e, t)} IS ${lit(e, comment)};`);
    for (const c of cols) if (c.comment.trim()) out.push(`COMMENT ON COLUMN ${tbl(e, t)}.${q(e, c.name)} IS ${lit(e, c.comment)};`);
  }
  if (e === "sqlserver") {
    if (comment.trim()) out.push(msDescription(t, null, comment));
    for (const c of cols) if (c.comment.trim()) out.push(msDescription(t, c.name, c.comment));
  }
  return out;
}

/** O CREATE da tabela montado a partir do catálogo (o SQLite guarda o original — aí vai ele). Inclui índices e chaves estrangeiras. */
export function createFromInfo(e: E, info: TableInfo & { comment?: string; ddl?: string }): string {
  const t = { schema: info.schema, name: info.name };
  const parts: string[] = [];
  if (info.ddl) parts.push(info.ddl.trim().replace(/;?$/, ";"));
  else parts.push(...createTable(e, t, info.columns.map(c => ({ name: c.name, type: c.type, nullable: c.nullable, default: c.default ?? "", identity: c.identity,
    pk: c.pk > 0, comment: (c as TCol).comment || "" })).map(c => ({ ...c, default: e === "sqlserver" ? c.default.replace(/^\((.*)\)$/s, "$1") : c.default })), info.comment || ""));
  for (const ix of info.indexes.filter(i => !i.primary)) parts.push(...createIndex(e, t, ix.name, ix.columns, ix.unique));
  if (!info.ddl) for (const fk of info.fks) parts.push(`ALTER TABLE ${tbl(e, t)} ADD CONSTRAINT ${q(e, fk.name)} FOREIGN KEY (${fk.columns.map(c => q(e, c)).join(", ")})` +
    ` REFERENCES ${tbl(e, { schema: fk.refSchema, name: fk.refTable })} (${fk.refColumns.map(c => q(e, c)).join(", ")});`);
  return parts.join("\n\n");
}
